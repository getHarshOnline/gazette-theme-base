#!/usr/bin/env python3
"""Run every Base self-test: the attribute inventory, the Node and browser suite and the native Gazette fixtures."""
import argparse
import os
from pathlib import Path
import subprocess
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gazette', required=True, type=Path, help='Exact built Gazette executable')
    parser.add_argument('--sdk', type=Path, help='Gazette sdk/js/browser-resources.toml for optional analytics and WebMCP checks')
    parser.add_argument('--node', default='node', help='Node executable used by the runtime fixtures')
    args = parser.parse_args()
    binary = args.gazette.resolve(strict=True)
    checks = [[sys.executable, str(ROOT / 'fixtures' / 'attributes.py')],
              [sys.executable, str(ROOT / 'fixtures' / 'attributes_test.py')],
              # The same Node suite as `npm test`, including the browser self-tests.
              [args.node, '--test', *map(str, sorted((ROOT / 'fixtures').glob('*.test.mjs')))]]
    for fixture, options in [
        ('reading', ['--preferred-sources', '--keep']), ('documentation', []), ('about-anatomy', []), ('search-page', []),
        ('service-closing', []), ('deployment', []), ('frames', []), ('resolved-links', []), ('feeds', []),
    ]:
        checks.append([sys.executable, str(ROOT / 'fixtures' / f'{fixture}.py'), '--gazette', str(binary), *options])
    if args.sdk:
        sdk = args.sdk.resolve(strict=True)
        for fixture in ['analytics', 'webmcp']:
            checks.append([sys.executable, str(ROOT / 'fixtures' / f'{fixture}.py'), '--gazette', str(binary), '--sdk', str(sdk)])
    else:
        print('Analytics and WebMCP native integration checks require --sdk; they are not included in this run.', flush=True)
    # Gazette captures the Theme tree, so keep generated bytecode out of it.
    environment = dict(os.environ, PYTHONDONTWRITEBYTECODE='1')
    failures = []
    reading_fixture = None
    for command in checks:
        print('CHECK:', ' '.join(command[:3]), flush=True)
        fixture_name = Path(command[1]).stem
        if fixture_name == 'resolved-links':
            if reading_fixture is None:
                failures.append((command, 'reading fixture unavailable'))
                continue
            command += ['--fixture', str(reading_fixture)]
        result = subprocess.run(command, cwd=ROOT, env=environment, check=False, capture_output=fixture_name == 'reading', text=True)
        if fixture_name == 'reading':
            print(result.stdout, end='')
            print(result.stderr, end='', file=sys.stderr)
            for line in result.stdout.splitlines():
                if line.startswith('native output: '):
                    candidate = Path(line.removeprefix('native output: ')).parents[1]
                    if candidate.name.startswith('base-reading-') and (candidate / 'workspace.toml').is_file():
                        reading_fixture = candidate
        if result.returncode:
            failures.append((command, result.returncode))
    for command, code in failures:
        print(f'FAILED ({code}): {command}', file=sys.stderr)
    if reading_fixture is not None:
        shutil.rmtree(reading_fixture)
    return bool(failures)


if __name__ == '__main__':
    sys.exit(main())
